/* ================= 像素风空状态图标 =================
     手写 SVG，每个 rect 就是「一个像素格」，和站点主题一致。
     不引图标库 —— 这点图形用不着。 */
  function px(rows, color) {
    var size = 4
    var w = rows[0].length
    var h = rows.length
    var out = '<svg viewBox="0 0 ' + w + ' ' + h + '" shape-rendering="crispEdges" aria-hidden="true">'
    for (var y = 0; y < h; y++) {
      for (var x = 0; x < w; x++) {
        var c = rows[y][x]
        if (c === '.') continue
        out += '<rect x="' + x + '" y="' + y + '" width="1" height="1" fill="' + (color[c] || color.d) + '"/>'
      }
    }
    return out + '</svg>'
  }

